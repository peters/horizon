#!/usr/bin/env bash
# A user-level `sshd` on a free loopback port, and the SSH alias that reaches it.
#
# The remote browser bridge lane needs an SSH target that answers without a
# prompt. A GitHub runner has no `sshd`, so this script starts one as the runner
# user and exports the alias that `remote_parity` reads. The `horizon-core`
# local-network test uses the same shape: a generated host key, one generated
# client key, `BatchMode`, and no password.
#
# In Actions the script appends the variables to `$GITHUB_ENV` and leaves the
# daemon running for the test step. Outside Actions it prints them and stops the
# daemon on exit.
set -euo pipefail

readonly root="${HORIZON_CI_SSH_ROOT:-$(mktemp -d)}"
readonly alias_name="horizon-ci-ssh"
readonly marker="# horizon-ci-ssh-transport: generated by scripts/ci-ssh-transport.sh"

if [[ "${RUNNER_OS:-}" != Linux && "${HORIZON_CI_SSH_FORCE:-}" != 1 ]]; then
    printf 'This transport is for Linux only; set HORIZON_CI_SSH_FORCE=1 to override.\n' >&2
    exit 2
fi

for tool in ssh-keygen ssh-keyscan ssh; do
    command -v "$tool" >/dev/null || {
        printf 'Missing %s; install openssh-server and openssh-client first.\n' "$tool" >&2
        exit 1
    }
done

sshd_bin="$(command -v sshd || printf '/usr/sbin/sshd')"
port_open() {
    (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null || return 1
    exec 3>&- 3<&-
    return 0
}
[[ -x "$sshd_bin" ]] || {
    printf 'Missing sshd; install openssh-server first.\n' >&2
    exit 1
}

mkdir -p "$root"
chmod 700 "$root"

# Debian and Ubuntu start `sshd` only when its privilege-separation directory
# exists. A user-level server creates none, so make it when the user may.
mkdir -p /run/sshd 2>/dev/null || true

# One client key. The server uses the host keys of the system, because Ubuntu's
# AppArmor profile and its defaults expect them under /etc/ssh, and it reads the
# authorized keys of the login account.
ssh-keygen -q -t ed25519 -N '' -C horizon-ci-ssh-transport -f "$root/client"

root_priv=0
if [[ "$(id -u)" == 0 ]]; then
    root_priv=1
elif sudo -n true 2>/dev/null; then
    root_priv=2
fi
run_root() {
    if [[ "$root_priv" == 1 ]]; then "$@"; else sudo -n "$@"; fi
}

mkdir -p "$HOME/.ssh"
chmod 700 "$HOME/.ssh"
if [[ -f "$HOME/.ssh/authorized_keys" ]]; then
    grep -v 'horizon-ci-ssh-transport' "$HOME/.ssh/authorized_keys" > "$root/authorized_keys.keep" || true
    mv "$root/authorized_keys.keep" "$HOME/.ssh/authorized_keys"
fi
cat "$root/client.pub" >> "$HOME/.ssh/authorized_keys"
chmod 600 "$HOME/.ssh/authorized_keys"

port=22
daemon_pidfile=""
started=0
if [[ "$root_priv" != 0 ]]; then
    # The system configuration: its host keys, its port and its authorized keys
    # are the paths that the login account and the Ubuntu defaults allow. The PID
    # file stays in this run's root, so a cleanup can never signal a system
    # server. A server that already answers on port 22 is left alone.
    if port_open 22; then
        printf 'A server already answers on 127.0.0.1:22; this run uses it.\n' >&2
    else
        run_root mkdir -p /run/sshd
        daemon_pidfile="$root/sshd.pid"
        if run_root "$sshd_bin" \
            -o ListenAddress=127.0.0.1 \
            -o Port=22 \
            -o PidFile="$root/sshd.pid" \
            -o PasswordAuthentication=no \
            -o KbdInteractiveAuthentication=no \
            -o PermitRootLogin=prohibit-password \
            -o UsePAM=no; then
            started=1
        fi
    fi
else
    # A developer computer without sudo: a user-level server with its own host key
    # on a free port, in its own session, so a person can run this script by hand.
    ssh-keygen -q -t ed25519 -N '' -f "$root/host"
    port="$(python3 -c 'import socket; s = socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1]); s.close()')"
    cat > "$root/sshd_config" <<EOF
Port $port
ListenAddress 127.0.0.1
HostKey $root/host
AuthorizedKeysFile $HOME/.ssh/authorized_keys
PidFile $root/sshd.pid
UsePAM no
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin prohibit-password
StrictModes no
AllowTcpForwarding yes
AllowLocalPortForwarding yes
LogLevel ERROR
EOF
    daemon_pidfile="$root/sshd.pid"
    setsid "$sshd_bin" -f "$root/sshd_config" </dev/null > "$root/sshd.log" 2>&1 &
    started=1
fi

# A local run must not leave a server, a key or an alias behind. A CI step must
# leave the server up for the test step, so the cleanup is bound to `GITHUB_ENV`.
stop=0
cleanup() {
    if [[ "$stop" == 1 || -n "${GITHUB_ENV:-}" ]]; then
        return 0
    fi
    stop=1
    if [[ "$started" == 1 && -n "$daemon_pidfile" && -f "$daemon_pidfile" ]]; then
        if [[ "$root_priv" == 0 ]]; then
            kill "$(cat "$daemon_pidfile" 2>/dev/null)" 2>/dev/null || true
        else
            run_root kill "$(cat "$daemon_pidfile" 2>/dev/null)" 2>/dev/null || true
        fi
    fi
    if [[ -f "$HOME/.ssh/authorized_keys" ]]; then
        grep -v 'horizon-ci-ssh-transport' "$HOME/.ssh/authorized_keys" > "$root/authorized_keys.keep" || true
        mv "$root/authorized_keys.keep" "$HOME/.ssh/authorized_keys"
        chmod 600 "$HOME/.ssh/authorized_keys"
    fi
    if [[ -f "$HOME/.ssh/config" ]]; then
        awk -v marker="# horizon-ci-ssh-transport: generated by scripts/ci-ssh-transport.sh" \
            -v alias="Host $alias_name" '
            $0 == marker { skip = 1; next }
            skip && $0 == alias { next }
            skip && /^  / { next }
            { skip = 0; print }
        ' "$HOME/.ssh/config" > "$root/config.keep" || true
        mv "$root/config.keep" "$HOME/.ssh/config"
        chmod 600 "$HOME/.ssh/config"
    fi
}
trap cleanup EXIT

for _ in {1..200}; do
    if (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null; then
        exec 3>&- 3<&-
        break
    fi
    sleep 0.05
done
if ! (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null; then
    printf 'sshd did not listen on 127.0.0.1:%s. Its log:\n' "$port" >&2
    cat "$root/sshd.log" >&2 2>/dev/null || true
    exit 1
fi
exec 3>&- 3<&-

# The generated host key is the only accepted key for this port.
ssh-keyscan -p "$port" 127.0.0.1 > "$root/known_hosts" 2>/dev/null
[[ -s "$root/known_hosts" ]] || {
    printf 'ssh-keyscan read no host key on 127.0.0.1:%s.\n' "$port" >&2
    exit 1
}

# Our alias goes first, because the first value of a keyword wins in an SSH
# configuration file and a later `Host *` must not replace the identity file.
mkdir -p "$HOME/.ssh"
chmod 700 "$HOME/.ssh"
existing="$HOME/.ssh/config"
scratch="$(mktemp)"
if [[ -f "$existing" ]]; then
    awk -v marker="$marker" -v alias="Host $alias_name" '
        $0 == marker { skip = 1; next }
        skip && $0 == alias { next }
        skip && /^  / { next }
        { skip = 0; print }
    ' "$existing" > "$scratch"
fi
{
    printf '%s\n' "$marker"
    printf 'Host %s\n' "$alias_name"
    printf '  HostName 127.0.0.1\n'
    printf '  Port %s\n' "$port"
    printf '  IdentityFile %s\n' "$root/client"
    printf '  IdentitiesOnly yes\n'
    printf '  UserKnownHostsFile %s\n' "$root/known_hosts"
    printf '  StrictHostKeyChecking yes\n'
    printf '  BatchMode yes\n\n'
    cat "$scratch"
} > "$existing"
chmod 600 "$existing"
rm -f "$scratch"

# Prove the transport before a test spends a minute on a skip.
if ! ssh -T -o BatchMode=yes -o ConnectTimeout=10 "$alias_name" true 2> "$root/ssh.err"; then
    printf 'The alias %s does not answer:\n' "$alias_name" >&2
    cat "$root/ssh.err" >&2 || true
    cat "$root/sshd.log" >&2 2>/dev/null || true
    exit 1
fi

export_lines="HORIZON_BROWSER_REMOTE_SSH_TARGET=$alias_name
HORIZON_BROWSER_REMOTE_REQUIRED=1
HORIZON_CI_SSH_ROOT=$root"

if [[ -n "${GITHUB_ENV:-}" ]]; then
    printf '%s\n' "$export_lines" >> "$GITHUB_ENV"
    printf 'Loopback SSH transport ready on 127.0.0.1:%s (alias %s).\n' "$port" "$alias_name"
else
    printf '%s\n' "$export_lines"
fi
